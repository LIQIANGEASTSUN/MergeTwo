end

function ConfigModel:_UpdateGeneralConfigs()
  local mapThemeState = self:IsServerControlOpen(EGeneralConfType.MapTheme)
  self.m_generalConfigs = {}
  if self.m_serverConfigs[ServerConfigKey.GeneralConf] and self.m_serverConfigs[ServerConfigKey.GeneralConf].config then
    local generalConfig = self.m_serverConfigs[ServerConfigKey.GeneralConf].config
    for _, val in ipairs(generalConfig) do
      local cfgType = val.confType
      if not self.m_generalConfigs[cfgType] then
        self.m_generalConfigs[cfgType] = {}
      end
      table.insert(self.m_generalConfigs[cfgType], val)
    end
  end
  if mapThemeState ~= self:IsServerControlOpen(EGeneralConfType.MapTheme) then
    EventDispatcher.DispatchEvent(EEventType.RefreshSettingStrongTip)
  end
end

function ConfigModel:GetGeneralConf(eGeneralConfType)
  if NeedRestartGeneralConfTypes[eGeneralConfType] and self.m_mapNeedRestartGeneralConfs[eGeneralConfType] then
    if self.m_mapNeedRestartGeneralConfs[eGeneralConfType] == Table.Empty then
      return nil
    end
    return self.m_mapNeedRestartGeneralConfs[eGeneralConfType]
  end
  local targetConfig
  local configs = self.m_generalConfigs[eGeneralConfType]
  if configs then
    local serverTime = GM.GameModel:HasServerTime() and GM.GameModel:GetServerTime()
    local index
    for i = 1, #configs do
      local c = configs[i]
      if not (c.eTime and serverTime) or serverTime < c.eTime then
        index = i
        break
      end
    end
    if index then
      local cfg = configs[index]
      if 1 < index and serverTime then
        for i = index - 1, 1, -1 do
          table.remove(configs, i)
        end
      end
      targetConfig = cfg
    end
  end
  if NeedRestartGeneralConfTypes[eGeneralConfType] then
    self.m_mapNeedRestartGeneralConfs[eGeneralConfType] = targetConfig or Table.Empty
  end
  return targetConfig
end

function ConfigModel:ParseGeneralConf(eGeneralConfType)
  local config = self:GetGeneralConf(eGeneralConfType)
  if Table.IsEmpty(config) then
    return nil
  end
  return config.param
end

