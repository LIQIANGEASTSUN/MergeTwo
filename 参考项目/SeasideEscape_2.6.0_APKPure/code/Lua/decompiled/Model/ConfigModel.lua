  if self.m_bubbleTimeConfig == nil or self.m_bubbleTimeConfigMD5 ~= configMD5 then
    self.m_bubbleTimeConfig = self:GetServerConfig(ServerConfigKey.BubbleTime) or {}
    table.sort(self.m_bubbleTimeConfig, function(a, b)
      return a.id > b.id
    end)
  end
  self.m_bubbleTimeConfigMD5 = configMD5
  local time = ItemBubble.Countdown
  for _, v in ipairs(self.m_bubbleTimeConfig) do
    if v.price.Right and price <= v.price.Right and price >= v.price.Left or price == v.price.Left then
      time = v.keep_time
      break
    end
  end
  return time
end

