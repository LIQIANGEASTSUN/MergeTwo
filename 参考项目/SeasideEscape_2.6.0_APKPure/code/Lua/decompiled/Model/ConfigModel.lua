function ConfigModel:GetReplacesFilePath(path)
  local fileName = path
  local lastSepIndex = StringUtil.rFindChar(path, ".")
  if lastSepIndex ~= nil then
    fileName = string.sub(path, lastSepIndex + 1)
  end
  if fileName == LocalConfigKey.MahjongGame or fileName == LocalConfigKey.TinyGameLevel then
    local suffix = ""
    suffix = GM.TinyGameManager:GetSuffix(fileName)
    if StringUtil.IsNilOrEmpty(suffix) then
      suffix = self:GetFileSuffix(fileName)
      GM.TinyGameManager:SetSuffix(fileName, suffix)
    end
    return path .. suffix
  end
  return path .. self:GetFileSuffix(fileName)
end

function ConfigModel:GetFileSuffix(fileName)
  local suffix = ""
  local config = self:GetServerConfig(ServerConfigKey.FileReplace)
  if config then
    for i = 1, #config do
      if config[i].file == fileName then
        suffix = config[i].suffix
      end
    end
  end
  if fileName == "LevelConfig" and StringUtil.IsNilOrEmpty(suffix) then
    suffix = GM.MiscModel:Get(EMiscKey.NewUserGrowthFundLevelConfigSuffix) or ""
  end
  return suffix
end

