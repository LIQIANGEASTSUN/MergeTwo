function ConfigModel:_ParseLoopControl(config)
  if Table.IsEmpty(config and config.loop_control or nil) then
    return
  end
  local loop_control = Table.DeepCopy(config.loop_control, true)
  if Table.IsEmpty(loop_control) then
    return
  end
  local loop_control_expand = {}
  for _, oneConfig in pairs(loop_control) do
    if not Table.IsEmpty(oneConfig.week_set) then
      for _, loopConfig in pairs(oneConfig.week_set) do
        local oneLoopControl = Table.ShallowCopy(oneConfig)
        for k, v in pairs(loopConfig) do
          oneLoopControl[k] = v
        end
        oneLoopControl.id = tonumber(loopConfig.week_num) .. "_" .. tonumber(loopConfig.week_day) .. "_" .. tonumber(loopConfig.duration_day or 1)
        oneLoopControl.duration = oneLoopControl.week_duration
        oneLoopControl.cooldown = oneLoopControl.week_cooldown
        loop_control_expand[#loop_control_expand + 1] = oneLoopControl
      end
    end
  end
  if Table.IsEmpty(loop_control_expand) then
    return loop_control[1]
  end
  if not config.loop_time_parsed then
    config.loop_time_parsed = true
    for _, v in pairs(loop_control_expand) do
      v.start_time = math.max(config.sTime or 0, v.start_time)
      v.end_time = math.min(config.eTime or math.maxinteger, v.end_time)
    end
  end
  table.sort(loop_control_expand, function(a, b)
    if a.start_time ~= b.start_time then
      return a.start_time < b.start_time
    elseif a.week_num ~= b.week_num then
      return a.week_num < b.week_num
    elseif a.week_day ~= b.week_day then
      return a.week_day < b.week_day
    else
      return a.duration_day < b.duration_day
    end
  end)
  local current_time = GM.GameModel:GetServerTime()
  local current_loop_config = loop_control_expand[1]
  for _, one_loop_control in ipairs(loop_control_expand) do
    current_loop_config = one_loop_control
    if current_time >= one_loop_control.start_time and current_time < one_loop_control.end_time or current_time < one_loop_control.start_time then
      break
    end
  end
  return current_loop_config
end

function ConfigModel:_ParseLoopDay(config)
  if Table.IsEmpty(config and config.loop_day or nil) then
    return
  end
  if not config.origin_sTime then
    config.origin_sTime = config.sTime
    config.origin_eTime = config.eTime
    config.origin_rTime = config.rTime
  end
  local loop_config = config.loop_day[1]
  local curTime = GM.GameModel:GetServerTime()
  local curDay = math.floor((curTime - (config.origin_sTime or 0)) / 86400)
  local curRound = curDay // loop_config.round
  local round_start_time = config.origin_sTime + 86400 * loop_config.round * curRound
  local round_release_time = round_start_time + 86400 * loop_config.round - 1
  if not Table.IsEmpty(loop_config.single_days) then
    local find = false
    for _, day in ipairs(loop_config.single_days) do
      local day_start_time = round_start_time + 86400 * (day - 1)
      if not Table.IsEmpty(loop_config.range_hours) then
        for _, range in ipairs(loop_config.range_hours) do
          local start_time = day_start_time + 3600 * range.Left
          local end_time = start_time + 3600 * (range.Right - range.Left + 1) - 1
          local pre_time = start_time - loop_config.pre_min * 60
          local release_time = end_time + loop_config.release_min * 60
          if curTime >= pre_time and curTime <= release_time then
            self:_SetConfigTime(loop_config, start_time, end_time, math.min(round_release_time, release_time))
            loop_config.id = string.format("%d_%d_%d_%d", curRound, day, range.Left, range.Right)
            find = true
            break
          end
        end
      else
        local start_time = day_start_time
        local end_time = start_time + 86399
        local pre_time = start_time - loop_config.pre_min * 60
        local release_time = end_time + loop_config.release_min * 60
        if curTime >= pre_time and curTime <= release_time then
          self:_SetConfigTime(loop_config, start_time, end_time, math.min(round_release_time, release_time))
          loop_config.id = string.format("%d_%d", curRound, day)
          break
        end
      end
      if find then
        break
      end
    end
  elseif not Table.IsEmpty(loop_config.range_days) then
    for _, range in ipairs(loop_config.range_days) do
      local start_time = round_start_time + 86400 * (range.Left - 1)
      local end_time = start_time + 86400 * (range.Right - range.Left + 1) - 1
      local pre_time = start_time - loop_config.pre_min * 60
      local release_time = end_time + loop_config.release_min * 60
      if curTime >= pre_time and curTime <= release_time then
        self:_SetConfigTime(loop_config, start_time, end_time, math.min(round_release_time, release_time))
        loop_config.id = string.format("%d_%d_%d", curRound, range.Left, range.Right)
        break
      end
    end
  else
    local start_time = round_start_time
    local end_time = round_release_time
    self:_SetConfigTime(loop_config, start_time, end_time, end_time)
    loop_config.id = curRound
  end
  if loop_config.start_time == nil then
    self:_SetConfigTime(loop_config, 0, 0, 0)
  end
  loop_config.end_time = math.min(loop_config.end_time, config.origin_eTime)
  loop_config.release_time = math.min(loop_config.release_time, config.origin_rTime)
  local lockMins = tonumber(loop_config.protect_time)
  if lockMins ~= nil then
    loop_config.lockHours = lockMins / 60
  end
  return loop_config
end

function ConfigModel:_SetConfigTime(config, start_time, end_time, release_time)
  config.start_time = start_time
  config.end_time = end_time
  config.release_time = release_time
end

function ConfigModel:_GetParsedServerConfig(key)
  local config = self:_GetOriginalServerConfig(key)
  if config then
    local loop_control_parsed = self:_ParseLoopControl(config) or self:_ParseLoopDay(config)
    if loop_control_parsed then
      config.duration = loop_control_parsed.duration
      config.cooldown = loop_control_parsed.cooldown
      config.sTime = loop_control_parsed.start_time or config.sTime
      config.eTime = loop_control_parsed.end_time or config.eTime
      config.rTime = loop_control_parsed.release_time or config.rTime
      config.loopId = loop_control_parsed.id
      config.lockHours = loop_control_parsed.lockHours
    end
  end
  return config
end

function ConfigModel:GetServerConfig(key)
  return self:_GetParsedServerConfig(key)
end

function ConfigModel:GetServerConfigMD5(key)
  local config = self.m_serverConfigs[key]
  return config and config.md5 or ""
end

function ConfigModel:UpdateServerConfigs(data)
  self:_ClearCachedServerControl()
  local bChanged = false
  local mapChangedKeys = {}
  data = json.decode(data) or {}
  for key, config in pairs(self.m_serverConfigs) do
    if data[key] == nil then
      self.m_serverConfigs[key] = nil
      mapChangedKeys[key] = true
      bChanged = true
    end
  end
  for key, config in pairs(data) do
    if self.m_serverConfigs[key] == nil or self.m_serverConfigs[key].md5 ~= config.md5 then
      self.m_serverConfigs[key] = config
      mapChangedKeys[key] = true
      bChanged = true
    end
  end
  if bChanged then
    self.m_dbTable:Set(DBKEY, DBVALUE, json.encode(self.m_serverConfigs))
    self:_OnServerConfigChanged()
  end
  local eGameMode = GM.SceneManager:GetGameMode()
  if (mapChangedKeys[ServerConfigKey.FileReplace] or mapChangedKeys[ServerConfigKey.BuildingSeverExConfig]) and eGameMode ~= EGameMode.Loading then
    return true
  end
  return false
end

