function ConfigModel:_InitItemModelConfigTemplate()
  local itemScoreConfigs = require("Data.Config.ItemScore", true)
  local itemModelConfigs = require("Data.Config.ItemModelConfig", true)
  local originBubblePriceMap = {}
  local template = require("Data.Config.ItemModelTemplate", true)
  local count = #itemModelConfigs
  local removeMap = {}
  local originLevelMap = {}
  local comboConfig
  for i = count, 1, -1 do
    local v = itemModelConfigs[i]
    v.series = ItemUtility.GetChainNumber(v.Type)
    if template.bubblePriceUpdMap[v.series] then
      originBubblePriceMap[v.Type] = v.BubblePrice
    end
    if template.chainNumberMap[v.series] then
      itemModelConfigs[i] = itemModelConfigs[count]
      itemModelConfigs[count] = nil
      count = count - 1
      if v.Type:byte(1) == 112 then
        removeMap[v.Type] = true
      else
        local chainId = ItemUtility.GetChainIdByCode(v.Type)
        local level = tonumber(string.sub(v.Type, (StringUtil.rFindChar(v.Type, "_") or 0) + 1))
        originLevelMap[chainId] = math.max(originLevelMap[chainId] or 0, level)
      end
    end
    comboConfig = template.luckyProduceCombo[v.Type]
    if comboConfig then
      for k, cfg in pairs(comboConfig) do
        v[k] = cfg
      end
      self:TryUseLuckyProduceConfig(v)
    end
  end
  count = #itemScoreConfigs
  for i = count, 1, -1 do
    local v = itemScoreConfigs[i]
    if removeMap[v.producer] then
      itemScoreConfigs[i] = itemScoreConfigs[count]
      itemScoreConfigs[count] = nil
      count = count - 1
    end
  end
  Table.ListAppend(itemModelConfigs, template.configs)
  Table.ListAppend(itemScoreConfigs, template.scores)
  self.m_originBubblePriceMap = originBubblePriceMap
  self.m_originLevelMap = originLevelMap
  self.m_configs[LocalConfigKey.ItemScore] = itemScoreConfigs
  local eventConfig = require("Data.Config.HuntItemModelConfig", true)
  if eventConfig ~= nil then
    Table.ListAppend(itemModelConfigs, eventConfig)
    if GameConfig.IsTestMode() then
      for _, cfg in pairs(eventConfig) do
        if StringUtil.StartWith(cfg.Type, "hunt") then
          local spreadCalNum = 0
          if cfg.Spread_Weight and cfg.Spread_WeightType == ItemSpreadWeightType.RandomSequnce then
            for _, item in pairs(cfg.Spread_Weight) do
              spreadCalNum = spreadCalNum + item.Weight
            end
            if spreadCalNum ~= cfg.Spread_ItemMaxNumber then
              Log.Assert(false, "HuntItemModelConfig Error!!! \229\165\150\229\138\177\232\174\161\231\174\151\231\187\147\230\158\156\228\184\142\233\133\141\231\189\174\231\187\147\230\158\156\228\184\141\231\155\184\231\173\137! type is " .. cfg.Type)
            end
          end
        end
      end
    end
  end
  local huntMapItemModelConfig = require("Data.Config.ExploreItemModelConfig", true)
  if huntMapItemModelConfig ~= nil then
    Table.ListAppend(itemModelConfigs, huntMapItemModelConfig)
    if GameConfig.IsTestMode() then
      for _, cfg in pairs(huntMapItemModelConfig) do
        if StringUtil.StartWith(cfg.Type, "hunt") then
          local spreadCalNum = 0
          if cfg.Spread_Weight and cfg.Spread_WeightType == ItemSpreadWeightType.RandomSequnce then
            for _, item in pairs(cfg.Spread_Weight) do
              spreadCalNum = spreadCalNum + item.Weight
            end
            if spreadCalNum ~= cfg.Spread_ItemMaxNumber then
              Log.Assert(false, "ExploreItemModelConfig Error!!! \229\165\150\229\138\177\232\174\161\231\174\151\231\187\147\230\158\156\228\184\142\233\133\141\231\189\174\231\187\147\230\158\156\228\184\141\231\155\184\231\173\137! type is " .. cfg.Type)
            end
          end
        end
      end
    end
  end
  self.m_configs[LocalConfigKey.ItemModel] = itemModelConfigs
end

function ConfigModel:TryUseLuckyProduceConfig(config)
  if not self:IsLuckyProduceOpen() then
    return
