    config.Use_LuckyProduce = true
    config.Spread_Weight = config.Lucky_Spread_Weight
    config.Spread_WeightType = config.Lucky_Spread_WeightType
    if config.Lucky_Lucky ~= nil then
      config.Lucky = config.Lucky_Lucky
    end
    if config.Lucky_Amazing ~= nil then
      config.Amazing = config.Lucky_Amazing
    end
  end
end

